"""The project database: a raw layer per source, a cleaned core layer and the analyses'
results (docs/DATABASE.md).

Which database: `config/database.toml` names the targets (a local SQLite file, the server)
and the selected one; DATABASE_URL in the environment or `--target` overrides it. The
tables are created by the numbered SQL files in `migrations/`, written to run on PostgreSQL
too; `schema_version` records which have been applied. Loading and building run on SQLite
for now; `check` reads either.

    python -m stock_analysis.db init         create the file and apply the migrations
    python -m stock_analysis.db load-files   import the data already in data/ (no network)
    python -m stock_analysis.db build        rebuild the core layer from raw
    python -m stock_analysis.db status       rows per table
    python -m stock_analysis.db check        connection, schema and data present (any target)
"""

from __future__ import annotations

import os
import sqlite3
import tomllib
from datetime import UTC, datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
MIGRATIONS = Path(__file__).with_name("migrations")
CONFIG = ROOT / "config" / "database.toml"
DEFAULT_URL = "sqlite:///data/stock.db"
# The auto-numbered primary key, per dialect ({{ID}} in the migration files).
ID_COLUMN = {
    "sqlite": "INTEGER PRIMARY KEY",
    "postgresql": "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
}


def load_config(path: Path = CONFIG) -> dict:
    if not Path(path).exists():
        return {"selected": "local", "targets": {"local": {"url": DEFAULT_URL}}}
    return tomllib.loads(Path(path).read_text(encoding="utf-8"))


def target_settings(target: str | None = None, config: dict | None = None) -> dict:
    """The url (and password_env) of a target: --target, else DATABASE_URL, else selected."""
    config = config or load_config()
    if target is None and os.environ.get("DATABASE_URL"):
        return {"name": "DATABASE_URL", "url": os.environ["DATABASE_URL"]}
    name = target or config.get("selected", "local")
    targets = config.get("targets", {})
    if name not in targets:
        raise ValueError(f"No target {name!r} in config/database.toml (have: {', '.join(targets)})")
    settings = {"name": name, **targets[name]}
    if not settings.get("url"):
        raise ValueError(f"Target {name!r} has no url in config/database.toml yet")
    return settings


def dialect(url: str) -> str:
    if url.startswith("sqlite:///"):
        return "sqlite"
    if url.startswith(("postgresql://", "postgres://")):
        return "postgresql"
    raise ValueError(f"Unsupported database URL scheme: {url.split(':')[0]}")


def db_path(url: str | None = None) -> Path:
    """The SQLite file of `url`, or of the selected target."""
    url = url or target_settings()["url"]
    if dialect(url) != "sqlite":
        raise ValueError("Loading and building run on SQLite for now; use --target local")
    path = Path(url.removeprefix("sqlite:///"))
    return path if path.is_absolute() else ROOT / path


def migrations() -> list[tuple[int, Path]]:
    return sorted((int(p.name[:3]), p) for p in MIGRATIONS.glob("[0-9][0-9][0-9]_*.sql"))


def migration_sql(path: Path, dialect: str = "sqlite") -> str:
    return path.read_text(encoding="utf-8").replace("{{ID}}", ID_COLUMN[dialect])


def connect(path: Path | str | None = None) -> sqlite3.Connection:
    """Open the database, applying any new migrations, with foreign keys on."""
    path = Path(path) if path else db_path()
    path.parent.mkdir(parents=True, exist_ok=True)
    con = sqlite3.connect(path)
    con.row_factory = sqlite3.Row
    con.execute("PRAGMA foreign_keys = ON")
    con.execute("PRAGMA journal_mode = WAL")
    migrate(con)
    return con


def schema_version(con: sqlite3.Connection) -> int:
    tables = {r[0] for r in con.execute("SELECT name FROM sqlite_master WHERE type = 'table'")}
    if "schema_version" not in tables:
        if "raw_fetch" in tables:
            raise RuntimeError(
                "This database file predates the migrations. Delete it and run "
                "init, load-files and build again (everything in it comes from data/)."
            )
        return 0
    return con.execute("SELECT COALESCE(MAX(version), 0) FROM schema_version").fetchone()[0]


def migrate(con: sqlite3.Connection) -> int:
    current = schema_version(con)
    for version, path in migrations():
        if version > current:
            con.executescript(migration_sql(path))
            con.execute(
                "INSERT INTO schema_version (version, applied_at) VALUES (?, ?)",
                (version, datetime.now(UTC).isoformat(timespec="seconds")),
            )
            con.commit()
            current = version
    return current


def table_counts(con: sqlite3.Connection) -> dict[str, int]:
    names = [
        r[0]
        for r in con.execute(
            "SELECT name FROM sqlite_master WHERE type = 'table' AND name NOT LIKE 'sqlite_%' "
            "ORDER BY name"
        )
    ]
    return {n: con.execute(f"SELECT COUNT(*) FROM {n}").fetchone()[0] for n in names}
