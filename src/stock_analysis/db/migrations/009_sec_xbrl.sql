-- Migration 009: facts from full SEC filings (issue #29). SEC's company facts leave out facts
-- split by a dimension, such as the EPS of each share class (Visa reports diluted EPS only per
-- class: A, B-1, B-2, C). The sec_xbrl source reads the whole XBRL of the filings that report a
-- missing value (edgartools), keeps the files in raw_payload and stores the mapped facts here,
-- with their dimension.

CREATE TABLE raw_sec_xbrl_fact (
    raw_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fetch_id        BIGINT NOT NULL REFERENCES raw_fetch (fetch_id),
    cik             BIGINT NOT NULL,
    accn            TEXT NOT NULL,      -- the filing's accession number
    form            TEXT NOT NULL,      -- 10-K, 10-Q
    filed           DATE NOT NULL,
    concept         TEXT NOT NULL,      -- 'us-gaap:EarningsPerShareDiluted'
    axis            TEXT NOT NULL DEFAULT '',   -- 'us-gaap:StatementClassOfStockAxis'; '' = none
    member          TEXT NOT NULL DEFAULT '',   -- 'us-gaap:CommonClassAMember'
    unit            TEXT NOT NULL,      -- USD, USD/shares, shares
    period_start    DATE,               -- empty for an instant
    period_end      DATE NOT NULL,
    value           DOUBLE PRECISION NOT NULL,
    label           TEXT                -- the line's label in the filing
);
CREATE INDEX raw_sec_xbrl_fact_key ON raw_sec_xbrl_fact (cik, concept, period_end);
