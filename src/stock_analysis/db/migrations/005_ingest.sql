-- Migration 005: the scheduled ingest (issue #18). Two more raw sources (ECB rates, Yahoo's
-- reported quarterly EPS), the work queue and run log of the ingest job (ops_*), and a daily
-- snapshot of the data coverage for the dashboard.
--
-- ops_* : the pipeline's own state. Updated in place by the ingest job (stock_writer).

-- ---------------------------------------------------------------- raw

-- ECB reference rates: US dollars per one unit of each currency, on each day.
CREATE TABLE raw_ecb_rate (
    fetch_id        BIGINT NOT NULL REFERENCES raw_fetch (fetch_id),
    currency        TEXT NOT NULL,
    date            DATE NOT NULL,
    usd_per_unit    DOUBLE PRECISION NOT NULL,
    PRIMARY KEY (currency, date, fetch_id)
);

-- Yahoo's earnings dates: estimated and reported EPS per quarterly report (the adjusted EPS
-- of the own-history P/E). report_date is the day of the report, in New York time.
CREATE TABLE raw_yahoo_earnings (
    fetch_id        BIGINT NOT NULL REFERENCES raw_fetch (fetch_id),
    symbol          TEXT NOT NULL,
    report_date     DATE NOT NULL,
    eps_estimate    DOUBLE PRECISION,
    eps_reported    DOUBLE PRECISION,
    surprise_pct    DOUBLE PRECISION,
    PRIMARY KEY (symbol, report_date, fetch_id)
);

-- ---------------------------------------------------------------- ops (the ingest job)

-- One row per thing to fetch: a source and its request key (a symbol, a CIK as text,
-- 'SP:SPX' or 'all'). The job picks the due tasks, most needed first.
CREATE TABLE ops_task (
    source          TEXT NOT NULL,      -- tradingview | sec_tickers | sec_companyfacts | yahoo_prices | yahoo_statements | yahoo_earnings | ecb_rates
    request_key     TEXT NOT NULL,
    symbol          TEXT,               -- the company, for per-company tasks
    active          BOOLEAN NOT NULL DEFAULT TRUE,   -- false once a company leaves the universe
    status          TEXT NOT NULL DEFAULT 'pending'
                    CHECK (status IN ('pending', 'ok', 'empty', 'error')),
    attempts        INTEGER NOT NULL DEFAULT 0,      -- consecutive failures
    created_at      TIMESTAMP NOT NULL,
    last_attempt_at TIMESTAMP,
    last_success_at TIMESTAMP,
    next_due_at     TIMESTAMP NOT NULL,
    last_fetch_id   BIGINT REFERENCES raw_fetch (fetch_id),
    last_rows       INTEGER,            -- rows received by the last successful fetch
    last_error      TEXT,
    PRIMARY KEY (source, request_key)
);
CREATE INDEX ops_task_due ON ops_task (active, next_due_at);

-- One row per run of the job.
CREATE TABLE ops_run (
    run_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    started_at      TIMESTAMP NOT NULL,
    finished_at     TIMESTAMP,
    mode            TEXT NOT NULL CHECK (mode IN ('backfill', 'maintain')),
    host            TEXT,               -- where it ran
    status          TEXT NOT NULL CHECK (status IN ('running', 'ok', 'partial', 'failed')),
    requests        INTEGER NOT NULL DEFAULT 0,
    tasks_ok        INTEGER NOT NULL DEFAULT 0,
    tasks_failed    INTEGER NOT NULL DEFAULT 0,
    rows_stored     INTEGER NOT NULL DEFAULT 0,
    build_id        BIGINT REFERENCES core_build (build_id),
    summary         TEXT                -- JSON: per source requests, stops (rate limit, budget), errors
);

-- ---------------------------------------------------------------- out

-- The data coverage, once a day (python -m stock_analysis.db coverage). The headline numbers
-- are columns, so the trend is one query; everything else is in detail_json.
CREATE TABLE out_coverage_snapshot (
    snapshot_date   DATE PRIMARY KEY,
    computed_at     TIMESTAMP NOT NULL,
    universe        TEXT NOT NULL,      -- 'SP:SPX'
    companies       INTEGER NOT NULL,   -- members of the universe
    companies_covered INTEGER NOT NULL, -- every required value present or explained
    cells_required  INTEGER NOT NULL,
    cells_present   INTEGER NOT NULL,
    mode            TEXT,               -- the ingest mode the numbers lead to
    detail_json     TEXT NOT NULL
);
