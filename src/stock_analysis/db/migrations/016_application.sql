-- Migration 016: the application Claude uses (issue #60, docs/APPLICATION.md). Claude saves its
-- analyses, edits the watch list and asks for runs through the web API's operations only.

-- One analysis run: opened by Airflow before it starts Claude, submitted by Claude.
CREATE TABLE out_analysis_run (
    run_key         TEXT PRIMARY KEY,   -- Airflow's run id
    trading_day     DATE NOT NULL,      -- the US session analysed
    subjects_json   TEXT NOT NULL,      -- JSON list: 'market', symbols, 'summaries'
    opened_at       TIMESTAMP NOT NULL, -- UTC
    fired_at        TIMESTAMP,          -- just before the call that starts Claude
    session_id      TEXT,
    session_url     TEXT,
    submitted_at    TIMESTAMP,
    submit_note     TEXT,               -- what Claude says about the run
    rendered_at     TIMESTAMP,
    report_json     TEXT,               -- the files, the email, what failed (stock_analysis.report)
    emailed_at      TIMESTAMP           -- nobody on the list is left to email
);

-- One subject's analysis in a run. Saving again before the run is submitted replaces it.
CREATE TABLE out_analysis (
    run_key          TEXT NOT NULL REFERENCES out_analysis_run (run_key),
    subject          TEXT NOT NULL,     -- 'market', 'summaries' or a symbol
    reviewed         DATE NOT NULL,     -- the day Claude reviewed every section
    sections_json    TEXT NOT NULL,     -- JSON object: heading -> Markdown
    corrections_json TEXT NOT NULL DEFAULT '[]', -- EPS corrections shown in the report only
    saved_at         TIMESTAMP NOT NULL,
    saved_by         TEXT NOT NULL,
    PRIMARY KEY (run_key, subject)
);
CREATE INDEX out_analysis_subject ON out_analysis (subject, saved_at);

-- Who gets the reports by email. A removed person stays, inactive. Addresses are entered
-- through the application only, never in the repository (it is public).
CREATE TABLE user_report_recipient (
    email           TEXT PRIMARY KEY CHECK (email = lower(email)),
    name            TEXT,
    active          BOOLEAN NOT NULL,
    changed_at      TIMESTAMP NOT NULL, -- UTC
    changed_by      TEXT NOT NULL,
    reason          TEXT NOT NULL
);

-- One email per run and person, marked just before it is sent.
CREATE TABLE out_report_email (
    run_key         TEXT NOT NULL REFERENCES out_analysis_run (run_key),
    email           TEXT NOT NULL,
    marked_at       TIMESTAMP NOT NULL, -- UTC
    message_id      TEXT,               -- Brevo's answer; NULL: no answer, may have gone out
    PRIMARY KEY (run_key, email)
);

-- Every change to the watch list, so it can be read back and undone.
CREATE TABLE user_watchlist_change (
    change_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    at              TIMESTAMP NOT NULL, -- UTC
    by              TEXT NOT NULL,
    action          TEXT NOT NULL CHECK (action IN ('add', 'change', 'remove', 'undo')),
    symbol          TEXT NOT NULL,
    reason          TEXT NOT NULL,
    before_json     TEXT,               -- the stock's settings before (NULL: not on the list)
    after_json      TEXT                -- and after (NULL: removed)
);
CREATE INDEX user_watchlist_change_symbol ON user_watchlist_change (symbol, change_id);

-- Extra runs asked for (by Claude or Babak); Airflow picks up the ones not taken yet.
CREATE TABLE ops_run_request (
    request_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    at              TIMESTAMP NOT NULL, -- UTC
    by              TEXT NOT NULL,
    kind            TEXT NOT NULL CHECK (kind IN ('analysis', 'recompute')),
    subjects_json   TEXT NOT NULL,      -- JSON list; empty: all
    reason          TEXT NOT NULL,
    taken_at        TIMESTAMP,
    run_key         TEXT
);

-- Every call of an application operation.
CREATE TABLE ops_api_call (
    call_id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    at              TIMESTAMP NOT NULL, -- UTC
    caller          TEXT NOT NULL,      -- which key: 'claude' or 'scripts'
    operation       TEXT NOT NULL,      -- method and path
    status          INTEGER NOT NULL,
    detail          TEXT                -- the query's SQL, or why it was refused
);
CREATE INDEX ops_api_call_at ON ops_api_call (at);
