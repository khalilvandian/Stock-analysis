-- The orchestrated nightly pipeline (issue #30, docs/ORCHESTRATION.md). Airflow writes one
-- row per run and one per step, so a run can be checked from anywhere: the Claude evening
-- session reads the `ready` marker through the web API, and the morning audit
-- (python -m stock_analysis.pipeline audit) fails when a weekday has no finished run.

CREATE TABLE ops_pipeline_run (
    run_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pipeline        TEXT NOT NULL,      -- 'stock_nightly'
    run_key         TEXT NOT NULL UNIQUE, -- Airflow's dag_run_id
    run_date        DATE NOT NULL,      -- the US trading day the run is for
    started_at      TIMESTAMP NOT NULL, -- UTC
    ready_at        TIMESTAMP,          -- the data steps passed: the evening session may start
    finished_at     TIMESTAMP,
    status          TEXT NOT NULL CHECK (status IN ('running', 'ready', 'ok', 'failed')),
    host            TEXT,
    summary         TEXT                -- JSON: what each check found
);
CREATE INDEX ops_pipeline_run_date ON ops_pipeline_run (pipeline, run_date);

CREATE TABLE ops_pipeline_step (
    run_id          BIGINT NOT NULL REFERENCES ops_pipeline_run (run_id) ON DELETE CASCADE,
    step            TEXT NOT NULL,      -- the Airflow task id
    status          TEXT NOT NULL CHECK (status IN ('ok', 'failed', 'waiting')),
    at              TIMESTAMP NOT NULL, -- UTC, when the step reported
    detail          TEXT,               -- JSON or a short message
    PRIMARY KEY (run_id, step)
);
